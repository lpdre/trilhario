'use strict';
const assert=require('node:assert/strict');
const {timeValid,encodeRouteGeometry,decodeRouteGeometry,compactRouteGeometry,routeShapeFingerprint}=require('../assets/js/trilhario-routes.js');
const now=2000000000000;
assert.equal(timeValid(now-3000,10000,now),true);
assert.equal(timeValid(now-20000,10000,now),false);
assert.equal(timeValid(now+310000,10000,now),false);
assert.equal(timeValid(-1,10000,now),false);
const points=[[-8.64523,40.64027],[-8.64001,40.65001],[-8.62115,40.65985]];
const encoded=encodeRouteGeometry(points);
assert.ok(encoded.length>0);
const decoded=decodeRouteGeometry(encoded);
assert.deepEqual(decoded,points);
assert.deepEqual(decodeRouteGeometry('!!!'),[]);
assert.equal(encodeRouteGeometry([[0,0],[Infinity,5]]),'');
assert.equal(routeShapeFingerprint(points),routeShapeFingerprint(decoded));
assert.notEqual(routeShapeFingerprint(points),routeShapeFingerprint(points.concat([[-8.60,40.66]])));
const many=Array.from({length:2500},(_,i)=>[-8.6+i*.00001,40.6+i*.00001]);
assert.equal(compactRouteGeometry(many).length,1800);
assert.equal(compactRouteGeometry(points).length,points.length);
console.log('OK: TTL, codificação de coordenadas, amostragem e assinatura de traçado');
